def infer_node_domain(cid: str, label: str, summary: str, explicit_domain: str = "") -> str:
    """Classify a concept into one of the 12 canonical academic domains."""
    if explicit_domain:
        return explicit_domain
    hay = f"{cid} {label} {summary}".lower()
    for domain, keywords in _DOMAIN_RULES:
        if any(kw in hay for kw in keywords):
            return domain
    return FALLBACK_DOMAIN_CS
